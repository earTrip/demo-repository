-- estimated_sec을 실제 녹음본 길이로 교체한다.
--
-- 기존 값(45/60/45/240/40)은 대본 글자수 ÷ 315자/분으로 추정한 것이었고, 그마저도 v2 대본
-- 기준이었다. 2026-08-05 v3 확장본 녹음이 나오면서 실측이 가능해졌다 —
-- 아래 값은 mobile/assets/audio/s*.wav의 ffprobe로 실측한 재생 길이(초)다.
--
-- 주의: S3(261초)는 S3→S4 도보 시간(59m ≈ 60초)보다 길다. 큐시트 B-1의
-- "낭독 길이 ≤ 다음 씬까지 도보 시간" 규칙을 실제 콘텐츠가 위반한 상태다.
-- 재생이 끊기지는 않는다 — trackQueue가 재생 중이면 다음 씬을 큐에 붙인다 —
-- 하지만 보행자는 S4 지점에 서서 S3 이야기를 계속 듣게 된다. 동선이나 분량 조정이 필요하며
-- 이건 현장 QA 사항이라 데이터만 사실대로 반영하고 여기서 결론내지 않는다.
UPDATE scene SET estimated_sec = CASE scene_order
    WHEN 1 THEN 214   -- 03:34
    WHEN 2 THEN 275   -- 04:35
    WHEN 3 THEN 261   -- 04:21
    WHEN 4 THEN 245   -- 04:05
    WHEN 5 THEN 259   -- 04:19
    END
 WHERE course_id = 1;
